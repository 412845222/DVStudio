const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const Database = require('better-sqlite3');
const tmp = path.join(process.cwd(), '.dvs-electron-upgrade-test-' + Date.now() + '.db');
const db = new Database(tmp);
db.pragma('journal_mode = WAL');
db.exec('CREATE TABLE IF NOT EXISTS t (k TEXT, v TEXT)');
const info = db.prepare('INSERT INTO t (k, v) VALUES (?, ?)').run('electron', process.versions.electron);
const row = db.prepare('SELECT k, v FROM t WHERE k = ?').get('electron');
const count = db.prepare('SELECT COUNT(*) AS c FROM t').get().c;
db.close();
fs.unlinkSync(tmp);
process.stdout.write('OK electron=' + process.versions.electron + ' node=' + process.versions.node + ' modules=' + process.versions.modules + ' sqlite3_loaded=1 row=' + JSON.stringify(row) + ' count=' + count + '\n');
process.exit(0);
