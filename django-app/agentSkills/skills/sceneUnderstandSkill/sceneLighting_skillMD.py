		'若图像是低照度、电影感、夜景、暖调室内，请保持暗部，不要靠大面积 ambient/hemisphere 把整个房间打平。'
		'如果看到发亮天花或窗面，只能在“确实可见大面积发光面”的前提下输出 rect-area；否则应优先还原真实灯具的位置。'
