		'若参考图整体偏暗、电影感强、暗部保留明显，请默认这是低照度场景：ambientLight 和 hemisphereLight 必须非常弱，globalSettings.exposure 必须偏低。'
		'除非参考图中真的能看见大面积发光顶板、天窗或发光窗面，否则不要输出大尺寸 rect-area 作为主光。'
