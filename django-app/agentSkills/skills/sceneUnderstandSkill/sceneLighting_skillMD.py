		'若参考图中存在局部灯具，例如吊灯、台灯、壁灯、线性灯带，请尽量绑定到对应 layout 对象，填写 anchorObjectId。'
		'每个 light 最好补充 sourceKind、emitMode、fixtureShape，便于区分真实灯具、自发光面和混合型发光体。'
		'sourceKind 推荐使用 direct-light、practical-fixture、emissive-surface、motivated-light。'
		'emitMode 推荐使用 illuminates-scene、self-emissive-only、mixed。'
		'fixtureShape 推荐使用 bulb、tube、strip、panel、sconce、downlight、spot-head、window、screen。'
		'颜色建议使用 CSS 可识别颜色或 #RRGGBB。强度必须是适合 Three.js 预览的相对值，避免极端夸张。'
		'你必须理解当前前端预览器的真实运行规则，并按这些规则反推原始 JSON 数值。'
		'当前预览器使用 ACESFilmicToneMapping；globalSettings.exposure 会直接影响 toneMappingExposure。'
		'ambient、hemisphere、directional、point、spot、rect-area 在前端都会再次按类型缩放、并有强度上限。'
		'其中 rect-area 会被额外放大显示，strip/panel 类面光如果原始 intensity 写得过大，会在前端变成严重过曝。'
