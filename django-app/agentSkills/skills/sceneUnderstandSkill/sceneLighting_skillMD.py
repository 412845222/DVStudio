		'当前预览器对 rect-area 的 width/height 使用场景世界单位，而不是厘米。'
		'你必须使用与 layout JSON 相同的世界单位，不能把 40cm、60cm 直接写成 40、60。'
		'如果一个房间尺度只有数个单位，那么天花灯板宽高通常也应是 0.3 到 1.6 量级；灯带 height 常为 0.03 到 0.12。'
		'distance 同样必须使用场景世界单位，不能把厘米或毫米直接写进 JSON。'
		'如果 layout 中物体位置普遍在 -5 到 5 之间，那么 spot/point 的 distance 通常也应是 0.8 到 4.5，而不是 180 或 220。'
